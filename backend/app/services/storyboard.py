from ..schemas import StoryboardRequest


BEATS = [
    ("The opening frame", "Lead with the most visually striking establishing shot.", "0:00"),
    ("The journey", "Build anticipation with movement, roads, arrivals and changing scenery.", "0:06"),
    ("The experience", "Show the signature activity and the people who made the trip memorable.", "0:14"),
    ("The little moments", "Slow down for food, details, candid reactions and quiet discoveries.", "0:25"),
    ("The finale", "End on a wide view or warm closing moment, then let the image breathe.", "0:36"),
]


def _timeline(durations: list[float], target: int) -> list[tuple[int, int]]:
    weights = [max(0.1, float(value)) for value in durations]
    total = sum(weights)
    remaining = target
    cursor = 0
    result = []
    for index, weight in enumerate(weights):
        seconds = remaining if index == len(weights) - 1 else max(1, round(target * weight / total))
        seconds = min(seconds, remaining - (len(weights) - index - 1))
        result.append((cursor, seconds))
        cursor += seconds
        remaining -= seconds
    return result


def normalize_ai_storyboard(request: StoryboardRequest, generated: dict) -> dict:
    raw_scenes = generated.get("scenes")
    if not isinstance(raw_scenes, list) or len(raw_scenes) != 5:
        raise ValueError("The AI storyboard must contain exactly five scenes.")

    durations = []
    scenes = []
    for index, scene in enumerate(raw_scenes):
        if not isinstance(scene, dict):
            raise ValueError("The AI storyboard contains an invalid scene.")
        title = str(scene.get("title", "")).strip()
        direction = str(scene.get("direction", "")).strip()
        shot = str(scene.get("suggested_shot", "")).strip()
        if not title or not direction or not shot:
            raise ValueError("The AI storyboard is missing required scene details.")
        try:
            duration = float(scene.get("duration_seconds", 1))
        except (TypeError, ValueError):
            duration = 1
        durations.append(max(0.1, duration))
        scenes.append({
            "id": f"scene-{index + 1}",
            "title": title[:100],
            "direction": direction[:500],
            "suggested_shot": shot[:100],
        })

    timeline = _timeline(durations, request.target_duration_seconds)
    for scene, (start, seconds) in zip(scenes, timeline):
        scene["start_seconds"] = start
        scene["duration_seconds"] = seconds

    return {
        "title": str(generated.get("title") or f"{request.destination.strip() or 'Your trip'} — the story")[:140],
        "destination": request.destination,
        "mood": request.mood,
        "aspect_ratio": request.aspect_ratio,
        "target_duration_seconds": request.target_duration_seconds,
        "trip_summary": str(generated.get("trip_summary") or request.trip_description or "A story from your journey.")[:500],
        "scenes": scenes,
        "generation_mode": "ollama",
        "note": "Generated by your configured local Ollama model. This storyboard is based on your trip brief, not visual analysis of your footage.",
    }


def build_storyboard(request: StoryboardRequest) -> dict:
    duration = request.target_duration_seconds
    weights = [0.14, 0.20, 0.28, 0.20, 0.18]
    cursor = 0
    scenes = []
    for index, (title, direction, _) in enumerate(BEATS):
        seconds = max(3, round(duration * weights[index]))
        start = cursor
        cursor += seconds
        scenes.append({
            "id": f"scene-{index + 1}",
            "title": title,
            "direction": direction,
            "start_seconds": start,
            "duration_seconds": seconds,
            "suggested_shot": ["wide establishing", "movement", "action", "close-up / candid", "hero wide"][index],
        })

    return {
        "title": f"{request.destination.strip() or 'Your trip'} — the story",
        "destination": request.destination,
        "mood": request.mood,
        "aspect_ratio": request.aspect_ratio,
        "target_duration_seconds": duration,
        "trip_summary": request.trip_description.strip() or "A collection of moments from your journey.",
        "scenes": scenes,
        "generation_mode": "template",
        "note": "Deterministic starter storyboard. Install and start Ollama to generate a personalized storyboard with a local language model. This does not analyse your footage yet.",
    }
